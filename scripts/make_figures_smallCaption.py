#!/usr/bin/env python3
"""
Generate every data figure in the manuscript from the committed result sets.

Figures are emitted as pgfplots fragments under paper/paperB/fig/ and pulled
into main.tex with \\input. Nothing is typed by hand, so a figure cannot drift
away from the data behind it, and a reader who clones the repository can
regenerate all of them from the CSVs with one command.

Usage, from the project root:

    python scripts/make_figures.py

Reads:
    results/resonance/{jul,dec}_seed*.csv    violation, mechanism, forecast
    results/mitigation/jul_seed*.csv         mitigation curves and trade-off
    data/carbon_intensity.csv                diurnal profile of the trace

Writes one .tex per figure into paper/paperB/fig/, overwriting.
"""
import glob
import os
import re
import sys
from pathlib import Path

import pandas as pd
import numpy as np

BASIS = "attributed_gco2"
OUT = Path("paper/paperB/fig")
PLATEAU, FLANKS = [26, 27, 28], [18, 30]

# Marks cycle so the series stay distinguishable in print and in greyscale.
MARKS = ["*", "square*", "triangle*", "o", "diamond*", "pentagon*"]
DASH = ["solid", "densely dashed", "densely dotted", "dashdotted",
        "loosely dashed", "loosely dotted"]


def load(pattern, need_season=True):
    paths = sorted(glob.glob(pattern))
    if not paths:
        return None
    fr = []
    for p in paths:
        m = re.search(r"(jul|dec)_seed(\d+)\.csv$", os.path.basename(p))
        if not m:
            continue
        d = pd.read_csv(p)
        d["season"], d["seed"] = m.group(1), int(m.group(2))
        fr.append(d)
    if not fr:
        return None
    df = pd.concat(fr, ignore_index=True)
    return df[df.placement_valid]


def violations(df, arm="perfect", policies=None):
    """V(m) per (season, seed, policy, capacity), as in analyze_resonance.py."""
    d = df[df.foresight == arm] if "foresight" in df.columns else df
    if policies is not None:
        d = d[d.policy.isin(policies)]
    rows = []
    for k, g in d.groupby(["season", "seed", "policy", "total_capacity"]):
        g = g.sort_values("deadline_margin_h")
        best = None
        for _, r in g.iterrows():
            v = r[BASIS]
            rows.append(dict(zip(["season", "seed", "policy", "cap"], k))
                        | {"m": int(r.deadline_margin_h),
                           "V": np.nan if best is None else 100 * (v / best - 1)})
            best = v if best is None else min(best, v)
    return pd.DataFrame(rows).dropna(subset=["V"])


def series(sub, x="m", y="V", err=True):
    """One pgfplots coordinate block, with across-seed standard deviation."""
    g = sub.groupby(x)[y].agg(["mean", "std"]).fillna(0)
    if err:
        return "\n".join(f"  ({i},{r['mean']:.3f}) +- (0,{r['std']:.3f})"
                         for i, r in g.iterrows())
    return "\n".join(f"  ({i},{r['mean']:.3f})" for i, r in g.iterrows())


def axis(body, **opt):
    o = ",\n  ".join(f"{k.replace('_', ' ')}={v}" for k, v in opt.items())
    return ("\\begin{tikzpicture}\n\\begin{axis}[\n  " + o + ",\n"
            "  tick label style={font=\\scriptsize},\n"
            "  label style={font=\\small},\n"
            "  grid=major, grid style={gray!20},\n]\n"
            + body + "\n\\end{axis}\n\\end{tikzpicture}\n")


def figure(name, body, caption, label):
    OUT.mkdir(parents=True, exist_ok=True)
    txt = ("%% Generated by scripts/make_figures.py. Do not edit by hand;\n"
           "%% regenerate instead, so the figure cannot drift from the data.\n"
           "\\begin{figure}[!t]\n\\centering\n" + body
           + "\\caption{" + caption + "}\n\\label{" + label + "}\n\\end{figure}\n")
    (OUT / f"{name}.tex").write_text(txt)
    print(f"  wrote {OUT / (name + '.tex')}")


def plot(sub, legend, idx, err=True, x="m", y="V"):
    style = (f"mark={MARKS[idx % len(MARKS)]}, {DASH[idx % len(DASH)]}, thick, "
             "mark size=1.6")
    e = ", error bars/.cd, y dir=both, y explicit" if err else ""
    return (f"\\addplot+[{style}{e}] coordinates {{\n{series(sub, x, y, err)}\n}};\n"
            f"\\addlegendentry{{{legend}}}\n")


# --------------------------------------------------------------- the figures

def fig_violation(reso):
    b = ""
    for i, (lbl, sel) in enumerate([
            ("July, capacity 350", (reso.season == "jul") & (reso.cap == 350)),
            ("July, capacity 140", (reso.season == "jul") & (reso.cap == 140)),
            ("December, capacity 350", (reso.season == "dec") & (reso.cap == 350))]):
        b += plot(reso[sel], lbl, i)
    b += "\\draw[gray, dashed] (axis cs:10,0) -- (axis cs:50,0);\n"
    figure("viol", axis(
        b, width="\\columnwidth", height="5.6cm",
        xlabel="{Deadline margin $m$ (h)}",
        ylabel="{Violation $V(m)$ (\\%)}",
        xmin=10, xmax=50, xtick="{12,18,24,30,36,48}",
        legend_style=("{at={(0.5,-0.30)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Violation against deadline margin, both seasons.",
        "fig:viol")


def fig_mechanism(df):
    """Realised CI, crowding and host count, each indexed to the shortest margin.

    Indexing is not cosmetic. The three are in different units, a carbon
    intensity, a dimensionless ratio and a count of machines, so plotting them
    against one axis in their own units would be meaningless. What the figure
    has to show is the shape of each along the margin axis: two rise to a peak
    together while the third falls throughout.
    """
    d = df[(df.season == "jul") & (df.total_capacity == 350)
           & (df.foresight == "perfect") & (df.policy == "space+time")]
    g = d.groupby("deadline_margin_h").agg(
        G=(BASIS, "mean"), K=("attributed_kwh", "mean"),
        H=("peak_active_hosts", "mean"), C=("peak_to_mean_occupancy", "mean"))
    g["CI"] = g.G / g.K
    base = g.iloc[0]
    b = ""
    for i, (col, lbl) in enumerate([("CI", "realised carbon intensity"),
                                    ("C", "temporal crowding"),
                                    ("H", "active hosts")]):
        pts = "\n".join(f"  ({m},{100 * v / base[col]:.2f})"
                         for m, v in g[col].items())
        b += (f"\\addplot+[mark={MARKS[i]}, {DASH[i]}, thick, mark size=1.6] "
              f"coordinates {{\n{pts}\n}};\n\\addlegendentry{{{lbl}}}\n")
    b += "\\draw[gray, dashed] (axis cs:10,100) -- (axis cs:50,100);\n"
    figure("mech", axis(
        b, width="\\columnwidth", height="5.4cm",
        xlabel="{Deadline margin $m$ (h)}",
        ylabel="{Relative to margin 12 (\\%)}",
        xmin=10, xmax=50, xtick="{12,18,24,30,36,48}",
        legend_style=("{at={(0.5,-0.30)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Carbon timing, each series indexed to margin 12.",
        "fig:mech")
def fig_crowding(df):
    """Crowding against realised CI, separately per capacity.

    The capacities must not be pooled. A larger cap buys the planner both the
    freedom to reach the daily trough, which lowers realised intensity, and
    the room to pile into it, which raises crowding, so between capacities the
    two move in opposite directions. Every within-capacity correlation is
    positive while the pooled one is negative. Drawing the pooled fit next to
    the group fits makes that reversal visible instead of leaving a reader to
    find it and read it as a contradiction.
    """
    d = df[(df.foresight == "perfect") & (df.policy == "space+time")].copy()
    d["ci"] = d[BASIS] / d.attributed_kwh
    b, notes = "", []
    for i, cap in enumerate(sorted(d.total_capacity.unique())):
        s = d[d.total_capacity == cap]
        if len(s) < 3:
            continue
        pts = "\n".join(f"  ({r.peak_to_mean_occupancy:.4f},{r.ci:.2f})"
                         for _, r in s.iterrows())
        slope, icept = np.polyfit(s.peak_to_mean_occupancy, s.ci, 1)
        rr = np.corrcoef(s.peak_to_mean_occupancy, s.ci)[0, 1]
        lo, hi = s.peak_to_mean_occupancy.min(), s.peak_to_mean_occupancy.max()
        b += (f"\\addplot[only marks, mark={MARKS[i]}, mark size=1.2] "
              f"coordinates {{\n{pts}\n}};\n"
              f"\\addlegendentry{{capacity {int(cap)}, $r={rr:+.2f}$}}\n"
              f"\\addplot[thick, {DASH[i]}, forget plot, "
              f"domain={lo:.3f}:{hi:.3f}] {{{slope:.3f}*x + {icept:.3f}}};\n")
        notes.append((int(cap), rr))
    pslope, picept = np.polyfit(d.peak_to_mean_occupancy, d.ci, 1)
    pr = np.corrcoef(d.peak_to_mean_occupancy, d.ci)[0, 1]
    lo, hi = d.peak_to_mean_occupancy.min(), d.peak_to_mean_occupancy.max()
    b += (f"\\addplot[thick, gray, loosely dashdotted, domain={lo:.3f}:{hi:.3f}] "
          f"{{{pslope:.3f}*x + {picept:.3f}}};\n"
          f"\\addlegendentry{{pooled, $r={pr:+.2f}$}}\n")
    figure("crowd", axis(
        b, width="\\columnwidth", height="5.8cm",
        xlabel="{Peak-to-mean occupancy}",
        ylabel="{Realised CI (\\gcokwh)}",
        legend_style=("{at={(0.5,-0.28)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Realised intensity against crowding, per capacity.",
        "fig:crowd")
def fig_forecast(df):
    b = ""
    for i, arm in enumerate(["perfect", "forecast"]):
        v = violations(df, arm, ["space+time"])
        b += plot(v[(v.season == "jul") & (v.cap == 350)],
                  f"{arm} foresight", i)
    b += "\\draw[gray, dashed] (axis cs:10,0) -- (axis cs:50,0);\n"
    figure("fc", axis(
        b, width="\\columnwidth", height="5.2cm",
        xlabel="{Deadline margin $m$ (h)}",
        ylabel="{Violation $V(m)$ (\\%)}",
        xmin=10, xmax=50, xtick="{12,18,24,30,36,48}",
        legend_style=("{at={(0.5,-0.32)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Perfect foresight against the day-ahead forecast.",
        "fig:fc")


def fig_mitigation(mit):
    v = violations(mit, "perfect")
    # Short legend labels on purpose. The policy names are given in full in
    # the text and the table; spelled out here they run past the column edge.
    sel = ["baseline", "price 0.10", "price 0.50", "spread 5\\%"]
    raw = ["space+time", "space+time+price(0.10)", "space+time+price(0.50)",
           "space+time+spread(5%)"]
    b = ""
    for i, (lbl, pol) in enumerate(zip(sel, raw)):
        s = v[v.policy == pol]
        if s.empty:
            continue
        b += plot(s, lbl, i)
    b += "\\draw[gray, dashed] (axis cs:16,0) -- (axis cs:32,0);\n"
    figure("mitig", axis(
        b, width="\\columnwidth", height="5.6cm",
        xlabel="{Deadline margin $m$ (h)}",
        ylabel="{Violation $V(m)$ (\\%)}",
        xmin=16, xmax=32, xtick="{18,24,26,28,30}",
        legend_style=("{at={(0.5,-0.30)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Violation under the mitigated planners.",
        "fig:mitig")


def fig_tradeoff(mit):
    """Peak height and emissions against the congestion price."""
    v = violations(mit, "perfect")
    lam = [0.0, 0.10, 0.25, 0.50, 1.00, 2.00]
    h, e, g = [], [], []
    base = mit[(mit.policy == "space+time")
               & (mit.deadline_margin_h.isin(PLATEAU))].attributed_gco2_per_vm_hour.mean()
    for L in lam:
        pol = f"space+time+price({L:.2f})"
        s = v[v.policy == pol]
        if s.empty:
            continue
        per = [gs[gs.m.isin(PLATEAU)].V.mean() - gs[gs.m.isin(FLANKS)].V.mean()
               for _, gs in s.groupby("seed")]
        per = [p for p in per if np.isfinite(p)]
        h.append((L, float(np.mean(per)), float(np.std(per, ddof=1) / len(per) ** 0.5)))
        em = mit[(mit.policy == pol)
                 & (mit.deadline_margin_h.isin(PLATEAU))].attributed_gco2_per_vm_hour.mean()
        e.append((L, 100 * (em / base - 1)))
        g.append((L, mit[(mit.policy == pol)
                         & (mit.deadline_margin_h == 27)].max_region_share.mean()))
    hc = "\n".join(f"  ({L},{m:.3f}) +- (0,{s:.3f})" for L, m, s in h)
    ec = "\n".join(f"  ({L},{m:.3f})" for L, m in e)
    gc = "\n".join(f"  ({L},{m:.4f})" for L, m in g)
    body = (
        "\\begin{tikzpicture}\n\\begin{axis}[\n"
        "  width=0.86\\columnwidth, height=5.4cm,\n"
        "  xlabel={Congestion price $\\lambda$},\n"
        "  ylabel={Percentage points / per cent}, axis y line*=left,\n"
        "  xmin=-0.1, xmax=2.1, xtick={0,0.25,0.5,1,2},\n"
        "  tick label style={font=\\scriptsize}, label style={font=\\small},\n"
        "  grid=major, grid style={gray!20},\n"
        "  legend style={at={(0.5,-0.30)}, anchor=north, legend columns=2,\n"
        "                font=\\scriptsize, draw=none, column sep=1.2ex},\n]\n"
        f"\\addplot+[mark=*, thick, mark size=1.6, error bars/.cd, y dir=both, "
        f"y explicit] coordinates {{\n{hc}\n}};\n"
        "\\addlegendentry{peak height}\n"
        f"\\addplot+[mark=square*, densely dashed, thick, mark size=1.6] "
        f"coordinates {{\n{ec}\n}};\n"
        "\\addlegendentry{emissions vs baseline}\n"
        # A pgfplots legend cannot reach across axis environments, so the
        # third series, which lives on the right-hand axis, is given a legend
        # entry here with no data attached to it. Without this the reader sees
        # an unlabelled curve and a right axis with nothing pointing at it.
        "\\addlegendimage{mark=triangle*, densely dotted, thick, black, "
        "mark size=1.8}\n"
        "\\addlegendentry{regional concentration}\n"
        "\\draw[gray, dashed] (axis cs:-0.1,0) -- (axis cs:2.1,0);\n"
        "\\end{axis}\n"
        "\\begin{axis}[\n"
        "  width=0.86\\columnwidth, height=5.4cm, axis y line*=right,\n"
        "  axis x line=none, xmin=-0.1, xmax=2.1, ymin=0, ymax=1.05,\n"
        "  ylabel={Regional concentration}, ylabel style={rotate=180},\n"
        "  tick label style={font=\\scriptsize}, label style={font=\\small},\n]\n"
        f"\\addplot+[mark=triangle*, densely dotted, thick, mark size=1.8, "
        f"color=black] coordinates {{\n{gc}\n}};\n"
        "\\end{axis}\n\\end{tikzpicture}\n")
    figure("tradeoff", body, "Peak height and emissions against $\\lambda$.",
           "fig:tradeoff")


def fig_diurnal(trace):
    d = pd.read_csv(trace)
    d["hod"] = d.hour % 24
    b = ""
    prof = d.groupby(["region", "hod"]).ci_gco2_per_kwh.mean().unstack()
    swing = ((prof.max(axis=1) - prof.min(axis=1)) / prof.mean(axis=1)).sort_values()
    for i, reg in enumerate(list(swing.index[:1]) + list(swing.index[-2:])):
        p = prof.loc[reg]
        pts = "\n".join(f"  ({h},{v:.2f})" for h, v in p.items())
        style = f"mark=none, {DASH[i % len(DASH)]}, thick"
        b += (f"\\addplot+[{style}] coordinates {{\n{pts}\n}};\n"
              f"\\addlegendentry{{{reg}, swing {100 * swing[reg]:.0f}\\%}}\n")
    figure("diurnal", axis(
        b, width="\\columnwidth", height="5.2cm",
        xlabel="{Hour of day (UTC)}",
        ylabel="{Carbon intensity (\\gcokwh)}",
        xmin=0, xmax=23, xtick="{0,4,8,12,16,20}",
        legend_style=("{at={(0.5,-0.32)}, anchor=north, legend columns=2, "
                      "font=\\scriptsize, draw=none, column sep=1.2ex}")),
        "Mean diurnal profile of the trace.",
        "fig:diurnal")


def main():
    reso_raw = load("results/resonance/*_seed*.csv")
    mit_raw = load("results/mitigation/*_seed*.csv")
    trace = Path("data/carbon_intensity.csv")
    made = 0
    if reso_raw is not None:
        v = violations(reso_raw, "perfect",
                       ["space+time"] + [p for p in reso_raw.policy.unique()
                                         if p.startswith("time@")])
        fig_violation(v[v.policy == "space+time"]); made += 1
        fig_mechanism(reso_raw); made += 1
        fig_crowding(reso_raw); made += 1
        fig_forecast(reso_raw); made += 1
    else:
        print("  results/resonance missing: skipped viol, mech, crowd, fc")
    if mit_raw is not None:
        fig_mitigation(mit_raw); made += 1
        fig_tradeoff(mit_raw); made += 1
    else:
        print("  results/mitigation missing: skipped mitig, tradeoff")
    if trace.exists():
        fig_diurnal(trace); made += 1
    else:
        print(f"  {trace} missing: skipped diurnal")
    print(f"\n{made} figures written to {OUT}")
    if made == 0:
        sys.exit("nothing generated; run from the project root")


if __name__ == "__main__":
    main()
